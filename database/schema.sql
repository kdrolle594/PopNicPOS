-- PopNic POS schema for Postgres (Supabase). Idempotent: safe to re-run.
-- Applied by `node server/migrate.js`. The old MySQL schema is kept in
-- database/phase1_schema.sql for reference only.

CREATE EXTENSION IF NOT EXISTS citext;

-- Keeps updated_at current (MySQL's ON UPDATE CURRENT_TIMESTAMP).
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS app_user (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_uid      VARCHAR(255) UNIQUE,
  user_type     TEXT NOT NULL CHECK (user_type IN ('customer', 'employee')),
  email         CITEXT UNIQUE,
  phone         VARCHAR(50),
  display_name  VARCHAR(255),
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_app_user_phone ON app_user (phone);

CREATE TABLE IF NOT EXISTS employee_profile (
  user_id        BIGINT PRIMARY KEY REFERENCES app_user (id) ON DELETE CASCADE,
  role           TEXT NOT NULL CHECK (role IN ('cashier', 'kitchen', 'manager', 'admin', 'driver')),
  location_code  VARCHAR(50),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS customer_profile (
  user_id         BIGINT PRIMARY KEY REFERENCES app_user (id) ON DELETE CASCADE,
  loyalty_points  INT NOT NULL DEFAULT 0 CHECK (loyalty_points >= 0),
  loyalty_tier    TEXT NOT NULL DEFAULT 'bronze' CHECK (loyalty_tier IN ('bronze', 'silver', 'gold', 'platinum')),
  total_spent     NUMERIC(10,2) NOT NULL DEFAULT 0,
  orders_count    INT NOT NULL DEFAULT 0,
  joined_date     TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_visit      TIMESTAMPTZ,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS menu_item (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(255) NOT NULL,
  category      VARCHAR(100) NOT NULL,
  price         NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  cost          NUMERIC(10,2) NOT NULL CHECK (cost >= 0),
  available     BOOLEAN NOT NULL DEFAULT TRUE,
  is_combo      BOOLEAN NOT NULL DEFAULT FALSE,
  points_value  INT NOT NULL DEFAULT 0 CHECK (points_value >= 0),
  metadata      JSONB NOT NULL DEFAULT '{}'::jsonb,
  image_url     VARCHAR(512),
  description   VARCHAR(280),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_menu_item_category ON menu_item (category);

CREATE TABLE IF NOT EXISTS inventory_item (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           CITEXT NOT NULL UNIQUE,
  quantity       NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  unit           VARCHAR(50) NOT NULL,
  reorder_level  NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
  cost_per_unit  NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (cost_per_unit >= 0),
  last_updated   TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS menu_item_inventory (
  menu_item_id       BIGINT NOT NULL REFERENCES menu_item (id) ON DELETE CASCADE,
  inventory_item_id  BIGINT NOT NULL REFERENCES inventory_item (id) ON DELETE RESTRICT,
  quantity_used      NUMERIC(12,3) NOT NULL CHECK (quantity_used > 0),
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (menu_item_id, inventory_item_id)
);
CREATE INDEX IF NOT EXISTS idx_mii_inventory_item_id ON menu_item_inventory (inventory_item_id);

CREATE TABLE IF NOT EXISTS option_group (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        CITEXT NOT NULL UNIQUE,
  min_select  SMALLINT NOT NULL DEFAULT 0 CHECK (min_select >= 0),
  max_select  SMALLINT NOT NULL DEFAULT 1 CHECK (max_select >= 0),
  sort_order  INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS option_choice (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id           BIGINT NOT NULL REFERENCES option_group (id) ON DELETE CASCADE,
  name               CITEXT NOT NULL,
  price_delta        NUMERIC(8,2) NOT NULL DEFAULT 0,
  available          BOOLEAN NOT NULL DEFAULT TRUE,
  is_default         BOOLEAN NOT NULL DEFAULT FALSE,
  inventory_item_id  BIGINT REFERENCES inventory_item (id) ON DELETE SET NULL,
  inventory_qty      NUMERIC(10,3),
  sort_order         INT NOT NULL DEFAULT 0,
  UNIQUE (group_id, name)
);
CREATE INDEX IF NOT EXISTS idx_option_choice_inventory ON option_choice (inventory_item_id);

CREATE TABLE IF NOT EXISTS menu_item_option_group (
  menu_item_id  BIGINT NOT NULL REFERENCES menu_item (id) ON DELETE CASCADE,
  group_id      BIGINT NOT NULL REFERENCES option_group (id) ON DELETE RESTRICT,
  sort_order    INT NOT NULL DEFAULT 0,
  PRIMARY KEY (menu_item_id, group_id)
);
CREATE INDEX IF NOT EXISTS idx_mog_group ON menu_item_option_group (group_id);

-- Order numbers come from a sequence (MySQL used MAX()+1 with a retry).
CREATE SEQUENCE IF NOT EXISTS customer_order_number_seq;

CREATE TABLE IF NOT EXISTS customer_order (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number        INT NOT NULL UNIQUE DEFAULT nextval('customer_order_number_seq'),
  order_type          TEXT NOT NULL DEFAULT 'dine_in' CHECK (order_type IN ('dine_in', 'pickup', 'delivery')),
  status              TEXT NOT NULL DEFAULT 'pending'
                      CHECK (status IN ('pending', 'preparing', 'ready', 'out_for_delivery', 'completed', 'cancelled')),
  total               NUMERIC(10,2) NOT NULL CHECK (total >= 0),
  customer_user_id    BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
  customer_name       VARCHAR(255),
  customer_phone      VARCHAR(50),
  table_number        INT,
  delivery_address    TEXT,
  delivery_lat        NUMERIC(10,7),
  delivery_lng        NUMERIC(10,7),
  driver_name         VARCHAR(100),
  driver_phone        VARCHAR(30),
  driver_user_id      BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
  queue_position      SMALLINT,
  eta_at              TIMESTAMPTZ,
  notes               TEXT,
  payment_method      TEXT CHECK (payment_method IN ('cash', 'card', 'digital')),
  points_earned       INT NOT NULL DEFAULT 0 CHECK (points_earned >= 0),
  points_redeemed     INT NOT NULL DEFAULT 0 CHECK (points_redeemed >= 0),
  points_credited     BOOLEAN NOT NULL DEFAULT FALSE,
  created_by_user_id  BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
  paid_by_user_id     BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
  paid_at             TIMESTAMPTZ,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at        TIMESTAMPTZ,
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER SEQUENCE customer_order_number_seq OWNED BY customer_order.order_number;
CREATE INDEX IF NOT EXISTS idx_customer_order_status ON customer_order (status);
CREATE INDEX IF NOT EXISTS idx_customer_order_created_at ON customer_order (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_customer_order_customer_phone ON customer_order (customer_phone);
CREATE INDEX IF NOT EXISTS idx_customer_order_customer_user_id ON customer_order (customer_user_id);
CREATE INDEX IF NOT EXISTS idx_customer_order_driver_status ON customer_order (driver_user_id, status);
CREATE INDEX IF NOT EXISTS idx_customer_order_created_by ON customer_order (created_by_user_id);
CREATE INDEX IF NOT EXISTS idx_customer_order_paid_by ON customer_order (paid_by_user_id);

CREATE TABLE IF NOT EXISTS order_item (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id          BIGINT NOT NULL REFERENCES customer_order (id) ON DELETE CASCADE,
  menu_item_id      BIGINT REFERENCES menu_item (id) ON DELETE SET NULL,
  line_name         VARCHAR(255) NOT NULL,
  quantity          INT NOT NULL CHECK (quantity > 0),
  unit_price        NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
  paid_with_points  BOOLEAN NOT NULL DEFAULT FALSE,
  notes             TEXT,
  customizations    JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_order_item_order_id ON order_item (order_id);
CREATE INDEX IF NOT EXISTS idx_order_item_menu_item_id ON order_item (menu_item_id);

CREATE TABLE IF NOT EXISTS driver_location (
  driver_user_id  BIGINT PRIMARY KEY REFERENCES app_user (id) ON DELETE CASCADE,
  lat             NUMERIC(10,7) NOT NULL,
  lng             NUMERIC(10,7) NOT NULL,
  updated_at      TIMESTAMPTZ NOT NULL,
  route_calc_at   TIMESTAMPTZ,
  route_calc_lat  NUMERIC(10,7),
  route_calc_lng  NUMERIC(10,7),
  route_stop_ids  VARCHAR(512),
  route_json      JSONB
);

CREATE TABLE IF NOT EXISTS audit_log (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id  BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
  action_type    VARCHAR(100) NOT NULL,
  entity_type    VARCHAR(100) NOT NULL,
  entity_id      VARCHAR(255) NOT NULL,
  payload        JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_audit_log_actor_user_id ON audit_log (actor_user_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_created_at ON audit_log (created_at DESC);

-- One-time data changes run by migrate.js, recorded so they never run twice.
CREATE TABLE IF NOT EXISTS app_data_migration (
  name        VARCHAR(100) PRIMARY KEY,
  applied_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- updated_at triggers
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['app_user', 'employee_profile', 'customer_profile', 'menu_item',
                           'inventory_item', 'menu_item_inventory', 'customer_order']
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_updated_at ON %1$I', t);
    EXECUTE format('CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON %1$I
                    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()', t);
  END LOOP;
END;
$$;

-- Only the Express server (a direct database login) reads and writes these
-- tables. Row level security with no policies keeps Supabase's public REST
-- API (anon and authenticated keys) out of them.
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['app_user', 'employee_profile', 'customer_profile', 'menu_item',
                           'inventory_item', 'menu_item_inventory', 'option_group', 'option_choice',
                           'menu_item_option_group', 'customer_order', 'order_item', 'driver_location',
                           'audit_log', 'app_data_migration']
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    -- The anon/authenticated roles exist on Supabase, not on a plain local Postgres.
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('REVOKE ALL ON %I FROM anon, authenticated', t);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON SEQUENCE customer_order_number_seq FROM anon, authenticated;
  END IF;
END;
$$;
